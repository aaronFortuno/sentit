    assert.equal(await page.locator('#teacher-audio').getAttribute('src'),null);
    assert.equal(await page.locator('.paper-review-watermark').count(),await page.locator('.paper').count());
    assert.equal(await page.locator('[data-complete-question]').count(),8);
    assert.match(await page.locator('#generation-plan .generation-summary').innerText(),/1 tall · 1 petició nova/);
    await settle();await page.screenshot({path:path.join(output,'worksheet.png')});
    await page.locator('#generation-plan [data-take="S015-T01"]').click();
    assert.equal(await page.locator('#answers-mode').getAttribute('aria-pressed'),'true');
    assert.equal(await page.locator('.paper-answer-label').count(),8);
    assert.equal(await page.locator('.paper-take').count(),1);
    const script=await page.locator('#paper').innerText();
    for(const text of ['Guió i anotacions','Avui visitem el taller','poca llum','mig segon','S015-L01','60 segons','30 segons'])assert(script.includes(text),text);
    assert(await noOverflow(),'Review pages keep all their content inside the A4 frame');
    await settle();await page.screenshot({path:path.join(output,'script.png')});
    await page.locator('#print').dispatchEvent('click');assert.equal(await page.evaluate(()=>window.printCalls),0);
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('.paper').first().isVisible(),false);
    assert.equal(await page.locator('.review-print-notice').isVisible(),true);
    await page.pdf({path:path.join(output,'blocked-print.pdf'),preferCSSPageSize:true});
