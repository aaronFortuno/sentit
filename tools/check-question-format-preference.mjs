import assert from 'node:assert/strict';
import { createQuestionFormatPreference, questionFormatPreferenceKey as key } from '../question-format-preference.js';
import { activities } from '../catalogue.js';
import { registerQuestionChoices, responseQuestion } from '../question-responses.js';
const data = new Map([['sentit-worksheet-activities', 'keep-layouts'], ['sentit.collections.v1', 'keep-collections']]);
const storage = { getItem:k=>data.get(k)??null, setItem:(k,v)=>data.set(k,v), removeItem:k=>data.delete(k) };
let preference = createQuestionFormatPreference(storage);
assert.equal(preference.mode(),null);
const saved = { questionMode:'open', questionModes:{lloc:'open'}, questions:{lloc:{lines:5,included:false}}, code:'Classe', imageWidth:65 };
assert.equal(preference.settings(saved,true).questionMode,'open');
preference.set('choice');
assert.equal(data.get(key),'choice');
preference = createQuestionFormatPreference(storage);
const effective = preference.settings(saved,true);
assert.equal(effective.questionMode,'choice');
assert.deepEqual(effective.questionModes,saved.questionModes);assert.deepEqual(effective.questions,saved.questions);assert.equal(effective.code,'Classe');assert.equal(effective.imageWidth,65);assert.equal(saved.questionMode,'open');
await registerQuestionChoices(activities);
const a=activities.find(a=>a.code==='S003'),q=a.questions.find(q=>q.id==='lloc');
assert.equal(responseQuestion(a,q,effective).responseMode,'open','Individual exception survives shared default');
assert.equal(responseQuestion(a,q,preference.settings({})).responseMode,'choice');
preference.clear();assert.equal(data.has(key),false);assert.equal(data.get('sentit-worksheet-activities'),'keep-layouts');assert.equal(data.get('sentit.collections.v1'),'keep-collections');
storage.setItem(key,'invalid');assert.equal(createQuestionFormatPreference(storage).mode(),null);
assert.throws(()=>preference.set('unknown'));
const broken=createQuestionFormatPreference({getItem(){throw Error('blocked')},setItem(){throw Error('blocked')},removeItem(){throw Error('blocked')}});broken.set('open');assert.equal(broken.settings({}).questionMode,'open');broken.clear();assert.equal(broken.mode(),null);
console.log('PASS · shared persisted format, old layouts and individual exceptions, isolated reset, invalid storage and session-only fallback.');
